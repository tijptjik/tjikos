"""Regenerate vector samples: uv run --with svgpathtools python scripts/morphs.py.
Only development-time dependency; shipped QML consumes the generated coordinates.
"""

import json
from copy import deepcopy
from pathlib import Path
from svgpathtools import svg2paths

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "notifications": "proicons/bell",
    "notifications_off": "proicons/bell-off",
    "coffee": "proicons/coffee-hot",
    "hotel": "bed",
    "nightlight": "proicons/moon",
    "light_mode": "proicons/brightness",
    "desktop_windows": "proicons/computer",
    "sports_esports": "proicons/game",
    "volume_up": "proicons/volume",
    "headphones": "proicons/headphones",
}
shapes = {}
for name, source in SOURCES.items():
    paths, attrs = svg2paths(str(ROOT / "qml/icons" / f"{source}.svg"))
    contours = []
    for path, attr in zip(paths, attrs):
        for part in path.continuous_subpaths():
            length = part.length()
            if length < 0.001:
                continue
            points = []
            for i in range(48):
                point = part.point(
                    part.ilength(length * i / 47)
                    if 0 < i < 47
                    else (0 if i == 0 else 1)
                )
                points.append([round(point.real, 4), round(point.imag, 4)])
            contours.append(
                dict(
                    points=points,
                    closed=part.isclosed(),
                    fill=attr.get("fill", "none") not in ("none", ""),
                    stroke=attr.get("stroke") is not None,
                    length=length,
                )
            )
    contours.sort(key=lambda c: -c.pop("length"))
    shapes[name] = contours

# Bell-off splits the bell outline and inserts a long slash. Length-ranked
# contours are not corresponding geometry: matching them folds the bell into
# the slash. Keep both outlines stationary and crossfade their small differences;
# the clapper is shared, and only the slash extends from its tip.
bell, clapper = shapes["notifications"]
off = shapes["notifications_off"]
slash = next(c for c in off if c["points"][0] == [20.719, 21.782])
outline = [c for c in off if c is not slash and c["points"] != clapper["points"]]
on_paths = [bell, *outline, clapper, slash]
shapes["notifications"] = deepcopy(on_paths)
shapes["notifications_off"] = deepcopy(on_paths)
for i in range(len(on_paths)):
    shapes["notifications"][i]["opacity"] = 1 if i in (0, len(on_paths) - 2) else 0
    shapes["notifications_off"][i]["opacity"] = 0 if i == 0 else 1
shapes["notifications"][-1]["points"] = [slash["points"][0]] * len(slash["points"])


def closed(contour):
    first, last = contour["points"][0], contour["points"][-1]
    return contour["closed"] or sum((a - b) ** 2 for a, b in zip(first, last)) < 0.000004


def phases(contour):
    """Equivalent traversals, preserving point order along each contour."""
    points = contour["points"]
    if closed(contour):
        ring = points[:-1]
        for direction in (ring, list(reversed(ring))):
            for offset in range(len(ring)):
                shifted = direction[offset:] + direction[:offset]
                yield shifted + [shifted[0]]
    else:
        yield points
        yield list(reversed(points))


def distance(a, b):
    return sum((x - y) ** 2 for p, q in zip(a, b) for x, y in zip(p, q))


def pair_bodies(a, b):
    """Match silhouettes; unrelated details fade in place, never trade roles."""
    left, right = deepcopy(shapes[a]), deepcopy(shapes[b])
    body_a, body_b = left[0], right[0]
    # Closed paths have no meaningful starting vertex. Search winding and phase
    # for the least total point travel instead of twisting SVG authoring order.
    if closed(body_a) and not closed(body_b):
        body_a["points"] = min(phases(body_a), key=lambda p: distance(p, body_b["points"]))
    else:
        body_b["points"] = min(phases(body_b), key=lambda p: distance(body_a["points"], p))
    # Closure is already represented by the repeated endpoint. An explicit
    # closePath would snap a closing edge on/off midway through cup -> bed.
    body_a["closed"] = body_b["closed"] = False
    details = left[1:] + right[1:]
    shapes[a] = [body_a] + deepcopy(details)
    shapes[b] = [body_b] + deepcopy(details)
    for i in range(len(details)):
        shapes[a][i + 1]["opacity"] = 1 if i < len(left) - 1 else 0
        shapes[b][i + 1]["opacity"] = 0 if i < len(left) - 1 else 1


for pair in [("coffee", "hotel"), ("nightlight", "light_mode"), ("desktop_windows", "sports_esports"), ("volume_up", "headphones")]:
    pair_bodies(*pair)

(ROOT / "qml/MorphData.js").write_text(
    "// Generated by scripts/morphs.py from licensed SVG sources.\nvar shapes="
    + json.dumps(shapes, separators=(",", ":"))
    + ";\n"
)
print("Generated", len(shapes), "morph shapes")
